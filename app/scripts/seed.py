async def seed(session):
    await indexing_lock(session)
    for category, names in PRODUCT_NAMES.items():
        for index, name in enumerate(names):
            if await session.scalar(select(Product.id).where(Product.name == name)):
                continue
            specs = {"демонстрационные_данные": True, "гарантия": "12 месяцев"}
            if category == "Ноутбуки":
                specs.update({"RAM": f"{8 + index * 8} ГБ", "SSD": "512 ГБ"})
            elif category == "Смартфоны":
                specs.update({"память": "128 ГБ" if index == 2 else "256 ГБ"})
            elif category == "Наушники":
                specs.update({"подключение": "Bluetooth", "цвет": "чёрный"})
            else:
                specs.update({"разрешение": "2560x1440", "частота": f"{60 + index * 30} Гц"})
            session.add(
                Product(
                    name=name,
                    category=category,
                    description=f"Тестовая карточка {name}. Все данные вымышлены.",
                    price=Decimal(19990 + index * 10000),
                    stock=0 if index == 4 else 5 + index,
                    specifications=specs,
                )
            )
    for question, answer, category in FAQ_DATA:
        if not await session.scalar(select(FAQ.id).where(FAQ.question == question)):
            session.add(FAQ(question=question, answer=answer, category=category))
    docs = {
        "demo:delivery": (
            "Условия доставки",
            "Доставляем по России. СДЭК и транспортные компании. Адрес, цена и срок фиксируются при оформлении заказа. Дополнительные нестандартные услуги требуют проверки оператором.",
        ),
        "demo:returns": (
            "Обращения по возврату",
            "Оператор уточняет товар, номер заказа, причину возврата и состояние комплекта. Бот не утверждает универсальные сроки возврата и не принимает решение по претензии.",
        ),
        "demo:security": (
            "Безопасность общения",
            "Не передавайте пароли, коды оплаты и данные банковской карты. Оператору достаточно номера заказа и описания вопроса.",
        ),
        "demo:store": (
            "О демо-магазине",
            "SupportAI — вымышленный магазин для демонстрации backend-проекта. Цены, остатки и характеристики демонстрационные, реальная продажа не производится.",
        ),
    }
    for source, (title, content) in docs.items():
        if not await session.scalar(select(KnowledgeDocument.id).where(KnowledgeDocument.source == source)):
            session.add(KnowledgeDocument(source=source, title=title, content=content))


async def main():
    async with Session() as session, session.begin():
        await seed(session)
    print("Seed complete: 20 products, 24 FAQ, 4 documents. Run app.scripts.reindex for embeddings.")


if __name__ == "__main__":
    asyncio.run(main())
